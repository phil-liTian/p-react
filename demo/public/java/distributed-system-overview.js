function renderDistributedSystemOverview(t) {

  const conclusion = ruleBox('info',
    `<strong>分布式系统 = 多台独立计算机通过网络协作，对用户呈现为"一台机器"。</strong><br><br>
    核心特征：<strong>进程独立、网络通信、共享状态、故障独立</strong>。<br>
    前端类比：你写过的微前端架构就是一种"分布式前端"——每个子应用独立部署、独立运行，通过路由和通信总线组合成统一页面。后端分布式就是把单机应用按职责拆开部署到多台机器上。`);

  // ── 为什么要分布式 ──────────────────────────────────────────────────────────────

  const whyRows = [
    ['单机性能瓶颈',  'CPU/内存/IO 物理上限',         '一台 64 核 256G 服务器扛不住百万 QPS'],
    ['单点故障',      '一台机器宕机全业务中断',         '电商大促时单台订单库宕机会导致整个交易停摆'],
    ['地理与合规',    '用户分布多地、数据合规要求',     '海外用户访问国内机房延迟 300ms+'],
    ['弹性扩缩容',    '流量峰值加机器、低谷减机器',     '双 11 流量是日常 10 倍，临时买 10 倍机器不现实'],
  ];
  const whyTable = compareCard(whyRows, ['痛点', '单机困境', '典型场景']);

  // ── 五大特征 ────────────────────────────────────────────────────────────────────

  const featureRows = [
    ['进程独立性',   '每台机器独立进程、独立内存',         '不能用单机的 volatile / 锁跨机器同步'],
    ['网络通信',     '机器之间靠 TCP/RPC 交换数据',         '网络可能丢包、延迟、分区'],
    ['资源共享',     '协同对外提供服务、共享数据',           '用户不感知后端是几台机器'],
    ['故障独立',     '一台宕机不影响其他机器',              '需要故障检测 + 自动转移'],
    ['并发性',       '多机器同时处理请求',                  '需要处理数据竞争与一致性'],
  ];
  const featureTable = compareCard(featureRows, ['特征', '说明', '对开发的影响']);

  // ── 透明性 ──────────────────────────────────────────────────────────────────────

  const transparencyBox = ruleBox('accent',
    `<strong>分布式的"透明性"：用户和开发者不需要感知系统是分布式的。</strong><br><br>
    • <strong>访问透明</strong>：调用 <code>orderService.create()</code> 不需要知道目标在本地还是远程。<br>
    • <strong>位置透明</strong>：DNS 域名 <code>api.example.com</code> 背后可能是任意机房。<br>
    • <strong>故障透明</strong>：某台机器宕机，请求自动转发到其他机器，用户无感知。<br>
    • <strong>复制透明</strong>：数据有 3 个副本，用户写一份读一份，不感知副本存在。<br><br>
    前端类比：你访问 <code>cdn.example.com/a.js</code> 不关心 CDN 命中哪个边缘节点，这就是位置透明。`);

  // ── 核心难题 ────────────────────────────────────────────────────────────────────

  const challengeRows = [
    ['数据一致性',   '多副本之间数据如何保持一致',         '强一致 vs 最终一致 trade-off'],
    ['网络不可靠',   '丢包、延迟、分区（脑裂）',           'CAP 定理：分区时只能在 C/A 选一个'],
    ['分布式事务',   '跨库操作要么全成功要么全回滚',       '2PC/TCC/Seata 等方案'],
    ['全局唯一 ID',  '多机器同时生成 ID 不能冲突',         '雪花算法、Leaf 等方案'],
    ['服务发现',     '机器 IP 经常变化，如何找到对方',     'Nacos / Eureka / Consul'],
    ['链路追踪',     '一个请求跨 5 个服务，日志如何串起来', 'TraceId + MDC + SkyWalking'],
  ];
  const challengeTable = compareCard(challengeRows, ['难题', '问题', '对应方案']);

  // ── 演进路径 ────────────────────────────────────────────────────────────────────

  const evolveRows = [
    ['1. 单体架构',     '一个 war 包部署到一台 Tomcat',                '简单、易调试、单点故障'],
    ['2. 垂直拆分',     '按业务拆成订单、用户、商品多个应用',           '独立部署、扩容、数据库仍共享'],
    ['3. 服务化 (SOA)', '服务注册 + RPC 调用，ESB 总线',               '服务治理、协议统一'],
    ['4. 微服务',       '每个服务独立库、独立部署、独立扩缩',           '技术栈灵活、运维复杂度上升'],
    ['5. 云原生',       '容器 + K8s + Service Mesh',                   '弹性伸缩、声明式部署'],
  ];
  const evolveTable = compareCard(evolveRows, ['阶段', '形态', '特点']);

  const evolveNote = ruleBox('warning',
    `<strong>不要一上来就微服务。</strong><br><br>
    分布式带来的复杂度（网络、一致性、运维）远超单体。通常的节奏：<br>
    ① 先单体跑通业务 → ② 流量上来后做读写分离 / 缓存 → ③ 真正遇到瓶颈再做服务拆分。<br>
    过早分布式 = 过早优化，是万恶之源。`);

  // ── 通信方式 ────────────────────────────────────────────────────────────────────

  const commRows = [
    ['HTTP / REST',  '通用、跨语言、调试简单',         '订单 API 调用用户 API'],
    ['RPC',          '快、强类型、像本地调用',         'Dubbo / gRPC，内部服务间高频调用'],
    ['消息队列',     '异步、解耦、削峰',              '下单后发消息通知库存，不阻塞主流程'],
    ['共享存储',     '不直接通信，通过数据库协调',     '多个服务读写同一份 MySQL'],
  ];
  const commTable = compareCard(commRows, ['通信方式', '特点', '典型场景']);

  // ── 8 谬误 ──────────────────────────────────────────────────────────────────────

  const fallaciesBox = ruleBox('danger',
    `<strong>分布式八大谬误（Sun 公司总结，每个开发者都会踩）：</strong><br><br>
    ① 网络可靠 ② 延迟为零 ③ 带宽无限 ④ 网络安全<br>
    ⑤ 拓扑不变 ⑥ 管理员只有一个 ⑦ 传输代价为零 ⑧ 网络同质<br><br>
    <strong>现实：</strong>每个谬误背后都是一个生产事故。例如"网络可靠"导致的超时重试，可能让一笔转账执行两次——必须做幂等设计。`);

  return articleShell(t, `
    ${section('核心结论', conclusion)}
    ${section('为什么要分布式？', whyTable)}
    ${section('分布式系统的五大特征', featureTable)}
    ${section('透明性：用户不该感知"分布式"', transparencyBox)}
    ${section('分布式带来的核心难题', challengeTable)}
    ${section('架构演进路径', evolveTable + evolveNote)}
    ${section('机器之间怎么通信？', commTable)}
    ${section('分布式八大谬误', fallaciesBox)}`);
}
